-- =====================================================================
-- Patch 002 — vehicle performance specs, edition flags and notifications.
--
-- Idempotent: safe to run several times against an existing database.
--
-- This patch mirrors the changes made in `database/schema.sql`
-- (the source of truth) so that a database created before this
-- feature is brought up to date without recreating the database.
-- =====================================================================

-- ---------------------------------------------------------------------
-- 1. Notification type
-- ---------------------------------------------------------------------

DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_type WHERE typname = 'notification_type'
    ) THEN
        CREATE TYPE notification_type AS ENUM (
            'new_vehicle',
            'special_edition',
            'limited_edition',
            'general'
        );
    END IF;
END $$;

-- ---------------------------------------------------------------------
-- 2. Vehicle columns (editorial specs + edition flags)
-- ---------------------------------------------------------------------

ALTER TABLE vehicles
    ADD COLUMN IF NOT EXISTS engine              varchar(120),
    ADD COLUMN IF NOT EXISTS torque_nm           integer,
    ADD COLUMN IF NOT EXISTS acceleration_0_100  numeric(4, 1),
    ADD COLUMN IF NOT EXISTS top_speed_kmh       smallint,
    ADD COLUMN IF NOT EXISTS consumption_l_100km numeric(4, 1),
    ADD COLUMN IF NOT EXISTS is_special          boolean NOT NULL DEFAULT false,
    ADD COLUMN IF NOT EXISTS is_limited          boolean NOT NULL DEFAULT false,
    ADD COLUMN IF NOT EXISTS edition_size        integer,
    ADD COLUMN IF NOT EXISTS announced_at        timestamptz NOT NULL DEFAULT now();

-- CHECK constraints, added only when missing.
-- The names below match the constraints generated by schema.sql.
DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint WHERE conname = 'vehicles_torque_nm_check'
    ) THEN
        ALTER TABLE vehicles
            ADD CONSTRAINT vehicles_torque_nm_check CHECK (torque_nm > 0);
    END IF;

    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint WHERE conname = 'vehicles_acceleration_0_100_check'
    ) THEN
        ALTER TABLE vehicles
            ADD CONSTRAINT vehicles_acceleration_0_100_check
            CHECK (acceleration_0_100 > 0);
    END IF;

    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint WHERE conname = 'vehicles_top_speed_kmh_check'
    ) THEN
        ALTER TABLE vehicles
            ADD CONSTRAINT vehicles_top_speed_kmh_check CHECK (top_speed_kmh > 0);
    END IF;

    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint WHERE conname = 'vehicles_consumption_l_100km_check'
    ) THEN
        ALTER TABLE vehicles
            ADD CONSTRAINT vehicles_consumption_l_100km_check
            CHECK (consumption_l_100km > 0);
    END IF;

    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint WHERE conname = 'vehicles_edition_size_check'
    ) THEN
        ALTER TABLE vehicles
            ADD CONSTRAINT vehicles_edition_size_check CHECK (edition_size > 0);
    END IF;
END $$;

-- ---------------------------------------------------------------------
-- 3. Notifications
-- ---------------------------------------------------------------------

CREATE TABLE IF NOT EXISTS notifications (
    id uuid PRIMARY KEY DEFAULT gen_random_uuid (),
    type notification_type NOT NULL DEFAULT 'general',
    title varchar(160) NOT NULL,
    message text,
    vehicle_id uuid REFERENCES vehicles (id) ON DELETE CASCADE,
    is_published boolean NOT NULL DEFAULT true,
    created_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_notifications_created
    ON notifications (created_at DESC);

CREATE INDEX IF NOT EXISTS idx_notifications_vehicle
    ON notifications (vehicle_id);
